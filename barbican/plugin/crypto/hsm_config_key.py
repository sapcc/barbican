"""HSM config-key helper.

Encrypts the HSM Crypto-User PIN at rest with AES-256-GCM under a symmetric
"HSM config key". The key is *loaded from a mounted file* and is **never**
generated by Barbican: if the key is absent or malformed we fail hard rather
than fall back to a self-generated key (which would silently defeat the
protection).

The at-rest envelope stored in ``hsm_partition_configs.credentials`` is::

    {"v": 1, "alg": "AES-256-GCM", "nonce": <b64>, "ciphertext": <b64>}

where ``ciphertext`` is the AES-GCM output with the 16-byte tag appended (the
``cryptography`` library appends it). The envelope fields are base64 strings so
the dict round-trips cleanly through the JSON column.

This module has no oslo dependency so it is importable from both the
``barbican-manage`` CLI (encrypt on write) and the runtime crypto plugin
(decrypt on read). The key-file path is passed in by the caller.
"""
import base64
import binascii
import os

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from barbican.common import exception
from barbican import i18n as u

ENVELOPE_VERSION = 1
ALG = "AES-256-GCM"
NONCE_LEN = 12
KEY_LEN = 32


class HSMConfigKeyError(exception.BarbicanException):
    """The HSM config key could not be loaded (missing/unreadable/wrong size).

    Raised on a missing path, an unreadable or empty key file, or a key whose
    decoded length is not exactly 32 bytes. Barbican must never recover from
    this by generating its own key.
    """


class HSMCredentialDecryptionError(exception.BarbicanException):
    """The stored CU-PIN envelope could not be decrypted/authenticated.

    Raised on a malformed envelope or an AES-GCM tag mismatch (tampering, or a
    wrong config key). Callers must let this propagate so the plugin refuses
    HSM login rather than proceeding with a bad PIN.
    """


def load_config_key(path):
    """Load and validate the AES-256 HSM config key from a mounted file.

    The file holds base64 text; we decode it and require exactly 32 raw bytes.
    Fails hard (``HSMConfigKeyError``) on a missing path, unreadable/empty
    file, or wrong key length. Never generates a key.
    """
    if not path:
        raise HSMConfigKeyError(
            u._("No HSM config key path configured; refusing to continue."))
    try:
        with open(path, "rb") as f:
            raw = f.read()
    except OSError as e:
        # Keep the OS detail (path/errno) but not any key bytes.
        raise HSMConfigKeyError(
            u._("Unable to read HSM config key file %(path)s: %(err)s") % {
                "path": path, "err": e})
    if not raw.strip():
        raise HSMConfigKeyError(
            u._("HSM config key file %(path)s is empty.") % {"path": path})
    try:
        key = base64.b64decode(raw.strip(), validate=True)
    except (binascii.Error, ValueError):
        raise HSMConfigKeyError(
            u._("HSM config key file %(path)s is not valid base64.") % {
                "path": path})
    if len(key) != KEY_LEN:
        raise HSMConfigKeyError(
            u._("HSM config key must be %(want)d bytes (AES-256); "
                "got %(got)d after base64 decode.") % {
                    "want": KEY_LEN, "got": len(key)})
    return key


def encrypt_pin(plaintext, key):
    """Encrypt the CU-PIN under ``key`` and return a JSON-safe envelope dict.

    A fresh 12-byte nonce is drawn from ``os.urandom`` (kernel CSPRNG) per
    call.
    """
    if not isinstance(key, bytes) or len(key) != KEY_LEN:
        raise HSMConfigKeyError(
            u._("Invalid HSM config key supplied for encryption."))
    nonce = os.urandom(NONCE_LEN)
    ciphertext = AESGCM(key).encrypt(nonce, plaintext.encode("utf-8"), None)
    return {
        "v": ENVELOPE_VERSION,
        "alg": ALG,
        "nonce": base64.b64encode(nonce).decode("ascii"),
        "ciphertext": base64.b64encode(ciphertext).decode("ascii"),
    }


def decrypt_pin(envelope, key):
    """Decrypt and authenticate a CU-PIN envelope; return the plaintext PIN.

    Raises ``HSMCredentialDecryptionError`` on a malformed envelope or a GCM
    tag mismatch (tampering / wrong key). The PIN is never placed in the
    exception message.
    """
    if not isinstance(key, bytes) or len(key) != KEY_LEN:
        raise HSMConfigKeyError(
            u._("Invalid HSM config key supplied for decryption."))
    try:
        if envelope.get("v") != ENVELOPE_VERSION:
            raise HSMCredentialDecryptionError(
                u._("Unsupported HSM credential envelope version: %(v)s") % {
                    "v": envelope.get("v")})
        if envelope.get("alg") != ALG:
            raise HSMCredentialDecryptionError(
                u._("Unsupported HSM credential envelope algorithm: %(a)s") % {
                    "a": envelope.get("alg")})
        nonce = base64.b64decode(envelope["nonce"], validate=True)
        ciphertext = base64.b64decode(envelope["ciphertext"], validate=True)
    except HSMCredentialDecryptionError:
        raise
    except (AttributeError, KeyError, TypeError, ValueError,
            binascii.Error) as e:
        raise HSMCredentialDecryptionError(
            u._("Malformed HSM credential envelope: %(err)s") % {"err": e})
    try:
        plaintext = AESGCM(key).decrypt(nonce, ciphertext, None)
    except InvalidTag:
        raise HSMCredentialDecryptionError(
            u._("HSM credential authentication failed (tag mismatch); "
                "refusing to use the stored PIN."))
    return plaintext.decode("utf-8")


def is_legacy_plaintext(cred):
    """True if ``cred`` is a legacy plaintext row ``{"password": ...}``.

    An encrypted envelope carries a ``v`` key; a legacy row does not.
    """
    return (isinstance(cred, dict)
            and "password" in cred
            and "v" not in cred)
